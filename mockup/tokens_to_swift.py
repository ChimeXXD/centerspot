# Generates Agmen/Design/Tokens.swift from the :root tokens in mockup/app.html (D-44), plus the kit palette (D-53),
# so the app starts from the approved mockup without retyping values. After this, the Swift file is the source of truth (D-12).
import pathlib, re

here = pathlib.Path(__file__).parent
css = re.search(r":root \{(.*?)\n  \}", (here / "app.html").read_text(), re.S).group(1)
var = dict(re.findall(r"--([\w-]+):\s*([^;]+);", css))

def rgba(value):
    value = value.strip()
    if value.startswith("#"):
        return f"RGBA(0x{value[1:].upper()})"
    r, g, b, a = [x.strip() for x in re.match(r"rgba\((.*)\)", value).group(1).split(",")]
    return f"RGBA(0x{int(r):02X}{int(g):02X}{int(b):02X}, alpha: {float(a)})"

camel = lambda name: re.sub(r"-(\w)", lambda m: m.group(1).upper(), name)
colours = ["bg", "surface", "surface-2", "surface-3", "hairline", "text", "muted", "accent", "accent-ink", "danger", "pitch-a", "pitch-b", "chalk",
           "away-inner", "away-ink", "ball", "run", "pass", "dribble", "press"]

# Kit palette (UI-BRIEF §2, D-53): fill, number ink, and a light outline only where the fill alone would vanish on the pitch.
KIT = {
    "lime": ("C6FF3D", "0B0F14", None), "coral": ("FF6B4A", "0B0F14", None), "blue": ("4C8DFF", "0B0F14", None),
    "red": ("FF5252", "0B0F14", None), "orange": ("FF9F1C", "0B0F14", None), "yellow": ("FFD84A", "0B0F14", None),
    "green": ("2BD67B", "0B0F14", None), "purple": ("B79CFF", "0B0F14", None), "black": ("15181C", "FFFFFF", "E6E9EC"),
    "white": ("F2F5F7", "0B0F14", None), "sky": ("5BC8FF", "0B0F14", None), "maroon": ("8C1D40", "FFFFFF", "F2F5F7"),
}

def text_style(name):
    weight, size = re.match(r"(\d+)\s+(\d+)px", var[name]).groups()
    return int(weight), int(size)

WEIGHT = {400: ".regular", 500: ".medium", 600: ".semibold", 700: ".bold", 800: ".heavy"}
styles = [("largeTitle", "t-largetitle", ".largeTitle"), ("title", "t-title", ".title2"), ("headline", "t-headline", ".headline"),
          ("body", "t-body", ".body"), ("caption", "t-caption", ".caption")]
px = lambda name: var[name].replace("px", "").strip()
ms = lambda name: f"{int(var[name].replace('ms', '').strip()) / 1000:g}"
ease = re.findall(r"[\d.]+", var["ease"])

out = ["// Generated by mockup/tokens_to_swift.py from mockup/app.html (D-44) and the kit palette (D-53).",
       "// From here on this file is the source of truth (D-12); change the look here, not in the mockup.",
       "import SwiftUI", "", "/// Floodlight Chalk design tokens: colours, kit palette, type, spacing, radius and motion.", "enum Tokens {",
       "    enum Colour {"]
out += [f"        static let {camel(c)} = {rgba(var[c])}" for c in colours]
out += ["    }", "", "    /// A kit colour: the disc fill, its number ink, and an outline for fills too close to the dark pitch.",
        "    struct Kit: Sendable, Hashable {", "        let fill: RGBA", "        let ink: RGBA", "        let outline: RGBA?", "    }", "",
        "    static func kit(_ colour: Side.Colour) -> Kit {", "        switch colour {"]
for key, (fill, ink, outline) in KIT.items():
    out.append(f"        case .{key}: Kit(fill: RGBA(0x{fill}), ink: RGBA(0x{ink}), outline: {f'RGBA(0x{outline})' if outline else 'nil'})")
out += ["        }", "    }", "", "    /// Nunito for numbers and interface, Kalam for handwritten step notes (D-44). Both scale with Dynamic Type.",
        "    enum Typeface {", '        static let uiName = "Nunito"', '        static let noteName = "Kalam"', ""]
for swift_name, css_name, rel in styles:
    w, s = text_style(css_name)
    out.append(f"        static let {swift_name} = Font.custom(uiName, size: {s}, relativeTo: {rel}).weight({WEIGHT[w]})")
note_size = re.match(r"\d+\s+(\d+)px", var["t-note"]).group(1)
out += [f"        static let note = Font.custom(noteName, size: {note_size}, relativeTo: .body)",
        "        /// Token numbers on the pitch scale with the board, not Dynamic Type.",
        "        static func number(size: CGFloat) -> Font { .custom(uiName, fixedSize: size).weight(.heavy) }", "    }", "",
        "    enum Space {"]
out += [f"        static let s{i}: CGFloat = {px(f's{i}')}" for i in range(1, 7)]
out += ["    }", "", "    enum Radius {", f"        static let sheet: CGFloat = {px('r-sheet')}", f"        static let item: CGFloat = {px('r-item')}", "    }", "",
        "    /// UI motion only; playback motion is the Timeline (SPEC §3). Reduce Motion swaps these for crossfades.", "    enum Motion {",
        f"        static let select: Double = {ms('d-select')}", f"        static let step: Double = {ms('d-step')}",
        f"        static let sheet: Double = {ms('d-sheet')}", f"        static let toast: Double = {ms('d-toast')}",
        f"        static func ease(_ duration: Double) -> Animation {{ .timingCurve({', '.join(ease)}, duration: duration) }}", "    }", "}", ""]
(here / "../Agmen/Design/Tokens.swift").write_text("\n".join(out))
print("Tokens.swift written:", len(out), "lines")
