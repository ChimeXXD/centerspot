// Writes CenterSpotTests/Fixtures/scenarios.json from mockup/scenarios.js (D-94): the app's `Scenario.build` must give
// these players, numbers and positions. Run: node mockup/gen_scenario_fixtures.js
const fs = require("fs"), vm = require("vm"), path = require("path");
const dir = __dirname, ctx = {};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(dir, "scenario-data.js"), "utf8") + fs.readFileSync(path.join(dir, "scenarios.js"), "utf8")
  + ";this.build=buildScenario;this.list=scenariosFor;this.all=SCENARIOS;", ctx);
// Shapes with every role group between them, on every size.
const shapes = ["4-3-3", "4-2-3-1", "3-5-2", "5-4-1", "4-1-2-1-2", "7-2-3-1", "7-3-3", "5-2-2", "5-1-2-1"];
const cases = [];
for (const id of shapes) {
  for (const sc of ctx.list(require_pitch(id))) for (const attacking of [true, false]) cases.push(JSON.parse(JSON.stringify(ctx.build(sc.id, id, attacking))));
}
function require_pitch(id) { return vm.runInContext(`formation(${JSON.stringify(id)}).pitch`, ctx); }
const catalogue = { full: ctx.list("full").map(s => s.id), sevenASide: ctx.list("sevenASide").map(s => s.id), fiveASide: ctx.list("fiveASide").map(s => s.id) };
const out = path.join(dir, "..", "CenterSpotTests", "Fixtures", "scenarios.json");
fs.writeFileSync(out, JSON.stringify({ note: "Generated by mockup/gen_scenario_fixtures.js; do not edit by hand.", catalogue, cases }) + "\n");
console.log(cases.length, "cases", (fs.statSync(out).size / 1024).toFixed(0), "KB");
