// Writes CenterSpotTests/Fixtures/scenarios.json from mockup/scenarios.js (D-94) and scenario-moves.json from
// mockup/scenario-motion.js (D-96): the app's `Scenario.build` and `ScenarioMotion.build` must give these players,
// numbers, positions, arrows and notes. Run: node mockup/gen_scenario_fixtures.js
const fs = require("fs"), vm = require("vm"), path = require("path");
const dir = __dirname, ctx = {};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(dir, "scenario-data.js"), "utf8") + fs.readFileSync(path.join(dir, "scenarios.js"), "utf8")
  + fs.readFileSync(path.join(dir, "scenario-motion.js"), "utf8")
  + ";this.build=buildScenario;this.list=scenariosFor;this.all=SCENARIOS;this.move=buildMotion;this.scripts=MOTIONS;", ctx);
// Shapes with every role group between them, on every size.
const shapes = ["4-3-3", "4-2-3-1", "3-5-2", "5-4-1", "4-1-2-1-2", "7-2-3-1", "7-3-3", "5-2-2", "5-1-2-1"];
const cases = [];
for (const id of shapes) {
  for (const sc of ctx.list(require_pitch(id))) for (const attacking of [true, false]) cases.push(JSON.parse(JSON.stringify(ctx.build(sc.id, id, attacking))));
}
function require_pitch(id) { return vm.runInContext(`formation(${JSON.stringify(id)}).pitch`, ctx); }
const catalogue = { full: ctx.list("full").map(s => s.id), sevenASide: ctx.list("sevenASide").map(s => s.id), fiveASide: ctx.list("fiveASide").map(s => s.id) };
const out = path.join(dir, "..", "CenterSpotTests", "Fixtures", "scenarios.json");
fs.writeFileSync(out, JSON.stringify({ note: "Generated by mockup/gen_scenario_fixtures.js; do not edit by hand.", catalogue, cases }) + "\n");
console.log(cases.length, "cases", (fs.statSync(out).size / 1024).toFixed(0), "KB");

// The moves: four shapes across the three sizes, every scenario each offers, both sides. Compact: per step its
// duration, note, home and away as [number, x, y], the ball [x, y], and arrows as [kind, [x, y, …]].
const moveShapes = ["4-3-3", "3-5-2", "7-2-3-1", "5-2-2"];
const moves = [];
for (const id of moveShapes) {
  for (const sc of ctx.list(require_pitch(id))) for (const attacking of [true, false]) {
    const steps = ctx.move(sc.id, id, attacking);
    moves.push({ id: sc.id, formation: id, attacking, steps: JSON.parse(JSON.stringify(steps)).map(st => ({
      d: st.duration, n: st.note,
      h: st.home.map(p => [p.number, p.x, p.y]), a: st.away.map(p => [p.number, p.x, p.y]), b: [st.ball.x, st.ball.y],
      w: st.arrows.map(ar => [ar.kind, ar.points.flatMap(p => [p.x, p.y])]),
    })) });
  }
}
const movesOut = path.join(dir, "..", "CenterSpotTests", "Fixtures", "scenario-moves.json");
fs.writeFileSync(movesOut, JSON.stringify({ note: "Generated by mockup/gen_scenario_fixtures.js; do not edit by hand.", moves }) + "\n");
console.log(moves.length, "moves", (fs.statSync(movesOut).size / 1024).toFixed(0), "KB");

// The scripts themselves, for the app to read (presets/scenario-moves.json): the cast as an ordered list, since
// the order decides who is picked.
const scripts = {};
for (const [id, m] of Object.entries(ctx.scripts)) {
  scripts[id] = { cast: Object.entries(m.cast || {}).map(([alias, entry]) => [alias, ...entry]), beats: m.beats, end: m.end,
                  ...(m.endDefending ? { endDefending: m.endDefending } : {}) };
}
fs.writeFileSync(path.join(dir, "..", "presets", "scenario-moves.json"),
  JSON.stringify({ note: "Generated by mockup/gen_scenario_fixtures.js from mockup/scenario-motion.js (D-96); do not edit by hand.", scripts }, null, 1) + "\n");
console.log(Object.keys(scripts).length, "scripts");
