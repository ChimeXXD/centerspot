# Writes mockup/hero.js from the project's own data, so the mockup never retypes positions, formations or roles.
import json, pathlib
here = pathlib.Path(__file__).parent
hero_path = here / "../examples/overlap-left.tactic"
data = {
    "HERO": json.loads(hero_path.read_text()),
    "HERO_BYTES": hero_path.stat().st_size,
    "FORMATIONS": json.loads((here / "../presets/formations.json").read_text())["formations"],
    "ROLES": json.loads((here / "../presets/roles.json").read_text())["roles"],
}
js = "// Generated by build.py from examples/ and presets/. Do not edit.\n"
js += "".join(f"const {k} = {json.dumps(v)};\n" for k, v in data.items())
(here / "hero.js").write_text(js)
print("hero.js written; hero is", data["HERO_BYTES"], "bytes")
